# ===============================================================
# utils/code_normalizer.py
# Converts plain ML scripts into standardized Optimizable classes
# ===============================================================

import ast
import json
import os
import re
import requests
from textwrap import indent
from pathlib import Path
from typing import Optional, List
from rich.console import Console

console = Console()


class CodeNormalizer:
    """Transforms a training script into an Optimizable-compatible class."""

    def __init__(self, script_path: Path):
        self.script_path = script_path
        self.source = script_path.read_text()

    def transform_to_optimizable(self, class_name: str = "AutoGeneratedModel") -> Optional[str]:
        """Converts the script into an Optimizable-compatible structure."""
        try:
            tree = ast.parse(self.source)
            params = self._extract_hyperparams(tree)
            default_hparams = {k: (v[0] if isinstance(v, list) and v else v) for k, v in params.items()}
            auc_block = self._extract_auc_block(tree)
            new_code = self._build_class_code(class_name, default_hparams, auc_block)
            return new_code.strip()
        except Exception as ex:
            console.print(f"[red]CodeNormalizer failed for {self.script_path.name}: {ex}[/red]")
            return None

    def _extract_hyperparams(self, tree: ast.AST) -> dict:
        params = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name) and any(kw in target.id.lower() for kw in ["param", "grid", "search"]):
                        if isinstance(node.value, ast.Dict):
                            for key_node, val_node in zip(node.value.keys, node.value.values):
                                key = self._get_literal(key_node)
                                val = self._get_literal(val_node)
                                params[key] = val
        return params

    def _get_literal(self, node):
        if isinstance(node, ast.Constant):
            return node.value
        elif isinstance(node, ast.List):
            return [self._get_literal(e) for e in node.elts]
        elif isinstance(node, ast.Tuple):
            return tuple(self._get_literal(e) for e in node.elts)
        else:
            try:
                return ast.unparse(node)
            except Exception:
                return str(node)

    def _extract_auc_block(self, tree: ast.AST) -> str:
        auc_lines = []
        lines = self.source.splitlines()
        for node in ast.walk(tree):
            if isinstance(node, ast.Assign):
                targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
                if "auc" in targets:
                    start, end = node.lineno - 1, getattr(node, "end_lineno", node.lineno)
                    auc_lines.extend(lines[start:end])
        if not auc_lines:
            for line in lines:
                if "json.dumps" in line:
                    auc_lines.append(line)
        return "\n".join(auc_lines)

    def _build_class_code(self, class_name: str, default_hparams: dict, auc_block: str) -> str:
        body = self._strip_prints()
        cleaned_logic_lines = []
        for line in body.splitlines():
            s = line.strip()
            if s.startswith(("import ", "from ")):
                cleaned_logic_lines.append(line)
                continue
            if re.match(r"^\s*auc\s*=", line) or ("json.dumps" in line and "auc" in line):
                continue
            cleaned_logic_lines.append(line)

        logic_block = indent("\n".join(cleaned_logic_lines).strip(), " " * 8)
        auc_block = indent(auc_block.strip(), " " * 8)

        return f"""import json
import pandas as pd
from sklearn.model_selection import train_test_split
from examples.contract import Optimizable, Hyperparameters, Metrics

class {class_name}(Optimizable):
    \"\"\"Auto-generated Optimizable class.\"\"\"
    DEFAULT_HPARAMS: Hyperparameters = {json.dumps(default_hparams, indent=4)}

    def run(self, hparams: Hyperparameters) -> Metrics:
        import warnings, os
        os.environ['PYTHONWARNINGS'] = 'ignore'
        warnings.filterwarnings('ignore')
        df = self.data.copy()
{logic_block}

{auc_block}
        return {{"auc": float(auc)}}

if __name__ == "__main__":
    data = pd.read_csv("data/train.csv")
    script = {class_name}(data)
    print(script.run(hparams={class_name}.DEFAULT_HPARAMS))
"""

    def _strip_prints(self) -> str:
        return "\n".join(l for l in self.source.splitlines() if not l.strip().startswith("print("))


