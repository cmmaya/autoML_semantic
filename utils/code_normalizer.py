LLM_PROMPT_TEMPLATE = """
You are an AutoML Python engineer.

Your task is to rewrite the following plain training script into a self-contained
Optimizable Python module that follows this contract structure:

───────────────────────────────────────────────────────────────
# <dataset>_baseline.py
\"\"\"A simple, optimizable baseline script.\"\"\"
import pandas as pd
from typing import Dict, Any
from examples.contract import Optimizable, DataFrame, Hyperparameters, Metrics

class <CustomName>(Optimizable):
    \"\"\"An optimizable script for the dataset.\"\"\"

    DEFAULT_HPARAMS: Hyperparameters = {{
        # default hyperparameters here
    }}

    def run(self, hparams: Hyperparameters) -> Metrics:
        \"\"\"Runs the training and evaluation pipeline.\"\"\"
        df = self.data.copy()
        # full pipeline (preprocessing, model, training, eval)
        auc = ...
        return {{'auc': auc}}

if __name__ == '__main__':
    data = pd.read_csv('data/train.csv')
    script = <CustomName>(data)
    baseline_metrics = script.run(hparams=<CustomName>.DEFAULT_HPARAMS)
    print(f"Baseline Run Metrics: {{baseline_metrics}}")
───────────────────────────────────────────────────────────────

Rewrite rules:
1. Wrap the given ML training code into a class that inherits from Optimizable.
2. Preserve all preprocessing, model, and parameter logic from the original script.
3. Add DEFAULT_HPARAMS based on parameter grid or model defaults.
4. Implement run(self, hparams: Hyperparameters) that returns {{'auc': auc}}.
5. Ensure the script runs directly via `if __name__ == '__main__'`.

Code quality requirements:
- Always import all libraries that are used. If any function references a namespace
  like `sklearn.something`, ensure `import sklearn` is present at the top.
- Do not invent or use non-existent models or classes. Use only valid models from:
  scikit-learn, XGBoost, or LightGBM.
- Use explicit imports whenever possible (e.g., `from sklearn.linear_model import LogisticRegression`).
- The code must be executable without undefined names or missing imports.
- The script must produce an AUC metric named exactly `auc` and return it as a float.
- Avoid any print statements inside `run()`. Only print in the main block.
- No markdown, explanations, or extra text — output only valid Python code.

--- SCRIPT START ---
{script_text}
--- SCRIPT END ---
"""


def normalize_scripts(scripts: List[str], llm: bool = False) -> List[str]:
    """
    Normalizes scripts into the Optimizable class format.
    - If llm=True, uses GPT-5 API rewrite only.
    - If llm=False, uses the standard AST-based CodeNormalizer only.
    """
    normalized = []
    api_key = os.getenv("GPT5_API_KEY")
    api_url = "https://api.openai.com/v1/chat/completions"

    for script_path in scripts:
        path = Path(script_path)
        text = path.read_text()

        if "class" in text and "Optimizable" in text:
            console.print(f"{path.name} already normalized.")
            normalized.append(str(path))
            continue

        console.print(f"Normalizing {path.name}...")

        # ==============================================================
        # LLM Mode (GPT-5 only)
        # ==============================================================
        if llm:
            if not api_key:
                console.print(f"Error: GPT5_API_KEY not set. Skipping {path.name}.")
                continue

            headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}
            payload = {
                "model": "gpt-5",
                "messages": [
                    {"role": "system", "content": "You are an expert AutoML Python engineer."},
                    {"role": "user", "content": LLM_PROMPT_TEMPLATE.format(script_text=text)},
                ],
            }

            try:
                r = requests.post(api_url, headers=headers, json=payload)
                r.raise_for_status()
                llm_code = r.json()["choices"][0]["message"]["content"]

                out_path = path.with_name(f"{path.stem}_optimizable.py")
                out_path.write_text(llm_code)
                normalized.append(str(out_path))
                console.print(f"Saved {out_path.name}")
            except Exception as e:
                console.print(f"GPT-5 normalization failed for {path.name}: {e}")
            continue

        # ==============================================================
        # Standard Mode (AST transformation only)
        # ==============================================================
        normalizer = CodeNormalizer(path)
        normalized_code = normalizer.transform_to_optimizable("AutoGeneratedModel")

        if not normalized_code:
            console.print(f"Standard normalization failed for {path.name}.")
            continue

        out_path = path.with_name(f"{path.stem}_optimizable.py")
        out_path.write_text(normalized_code)
        normalized.append(str(out_path))
        console.print(f"Saved {out_path.name}")

    return normalized
